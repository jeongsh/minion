/** Remove prose full stops without damaging URLs, decimals or Latin names. */
export function normalizeStudioPunctuation(text: string, personaId: string): string {
  if (personaId === "t1-partisan") return text;
  return text.replace(/https?:\/\/[^\s<>"'）)]+|(?:[\p{L}\p{N}_-]+\.)+[\p{L}\p{N}_-]+|[.。．…]+/gu, (match) => {
    if (/^https?:\/\//.test(match)) return match.replace(/[.。．…]+$/, "");
    // Preserve decimal/version and Latin dotted tokens, not unspaced Korean sentences.
    if (/^[\p{L}\p{N}_-]+\./u.test(match)) {
      return match.replace(/\./g, (dot, offset: number) => /[A-Za-z0-9]/.test(match[offset - 1]) && /[A-Za-z0-9]/.test(match[offset + 1]) ? dot : " ");
    }
    return " ";
  }).replace(/[^\S\r\n]+/g, " ").replace(/ +(?=\r?$)/gm, "").trim();
}

